'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ts=require('typescript');
const code=fs.readFileSync(path.join(__dirname,'../src/diagnostics.ts'),'utf8');
const begin=code.indexOf('  private async repair(') >= 0 ? code.indexOf('  private async repair(') : code.indexOf('  async repair(');
const end=code.indexOf('  private updateActiveStatus()', begin);
assert(begin>0 && end>begin);
const js=ts.transpileModule(`class Harness { ${code.slice(begin,end)} } module.exports=Harness;`,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const vscode={CodeActionKind:{QuickFix:1}, CodeAction:class {constructor(title,kind){this.title=title;this.kind=kind;}}, workspace:{applyEdit:async()=>true}};
const context={module:{exports:{}},exports:{},vscode,eligible:()=>true,digest:()=> 'qualified-bytes',diagnosticCode:x=>String(x)};
vm.runInNewContext(js,context);
const H=context.module.exports;
(async()=>{
 const h=new H();h.actions=new Map();h.snapshots=new Map();
 const doc={isClosed:false,uri:{toString:()=> 'file:///current'},getText:()=> 'bytes'};
 const diag={code:'portable.lineage-integrity.parent-target-mismatch'};
 const multi={id:'multi',title:'Cascade 4 descendants',kind:'replace-record-set',sourceSha256:'qualified-bytes',qualification:'deterministic-shared-core',diagnosticCodes:[diag.code],replacements:[{path:'a'},{path:'b'}]};
 h.actions.set(doc.uri.toString(),[multi]);
 h.refresh=async()=>({state:'degraded'});
 let prepared=0;
 h.workspaceEditForAction=async()=>{prepared++;return {state:'ready',edit:{}};};
 let actions=await h.codeActions(doc,{diagnostics:[diag]});
 assert.equal(actions.filter(a=>a.edit).length,0,'Quick Fix must never offer multi-file mutation');
 assert.equal(prepared,0);
 const r=await h.repair(doc);
 assert.equal(r.state,'selection-required','Repair Artifact requires explicit selection for cascade, even if it is sole action');
 assert.equal(r.actions.length,1);
 assert.equal(prepared,0);
 console.log('PASS lightbulb single-artifact only; cascade requires explicit Repair Artifact selection');
})().catch(e=>{console.error(e);process.exitCode=1});
