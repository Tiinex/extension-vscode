import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const siteRoot = path.resolve(process.argv[2] || process.env.TIINEX_SITE_ROOT || '');
if (!process.argv[2] && !process.env.TIINEX_SITE_ROOT) throw new Error('tiinex.shared-core.site-root-required');
const modulePath = path.join(siteRoot, 'src/tooling/portable/adapters/node/handoff.manufacture.bootstrap.js');
const { buildToolingBootstrapTransportFiles } = await import(pathToFileURL(modulePath).href);
const built = await buildToolingBootstrapTransportFiles({ runtimeRoot: siteRoot, delivery: 'embedded' });
const outRoot = path.join(ROOT, 'shared-core');
await rm(outRoot, { recursive: true, force: true });
for (const file of built.files) {
  const relative = String(file.path || '').replace(/^tiinex\.bootstrap\//, 'tiinex.bootstrap/');
  const target = path.join(outRoot, ...relative.split('/'));
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, Buffer.from(file.data));
}
const provenance = {
  schema: 'tiinex.vscode.shared-core-snapshot.v1',
  source: { repository: 'Tiinex/site', workspaceId: 'site' },
  bootstrapManifestSha256: built.summary.manifestSha256,
  runtimeRepresentationSha256: built.summary.representationSha256,
  runtimeFiles: built.summary.runtimeFiles,
  runtimeBytes: built.summary.runtimeBytes,
  boundary: 'Generated byte-for-byte from the shared Site portable Tooling bootstrap builder. This snapshot is executable shared core, not VS Code semantic authority.'
};
await writeFile(path.join(outRoot, 'provenance.json'), `${JSON.stringify(provenance, null, 2)}\n`, 'utf8');
console.log(JSON.stringify({ status: 'ready', ...provenance }));
